USE ROLE PSET2_PIPELINE;
USE WAREHOUSE PSET2_WH;
USE DATABASE PSET2_OULAD;
USE SCHEMA BRONZE;

SELECT 'student_info' AS dataset, COUNT(*) AS row_count FROM STG_STUDENT_INFO
UNION ALL SELECT 'registration', COUNT(*) FROM STG_STUDENT_REGISTRATION
UNION ALL SELECT 'courses', COUNT(*) FROM STG_COURSES
UNION ALL SELECT 'vle', COUNT(*) FROM STG_VLE
UNION ALL SELECT 'student_vle', COUNT(*) FROM STG_STUDENT_VLE;

SELECT DATASET, METRIC, VALUE, DENOMINATOR,
       ROUND(100.0 * VALUE / NULLIF(DENOMINATOR, 0), 4) AS PERCENT_OF_ROWS
FROM DQ_BRONZE_PROFILE
ORDER BY DATASET, METRIC;

-- Esta consulta devuelve cero filas si las relaciones completas se cumplen.
SELECT COUNT(*) AS ORPHAN_ROWS
FROM STG_STUDENT_VLE e
LEFT JOIN STG_STUDENT_INFO i ON e.ENROLLMENT_KEY = i.ENROLLMENT_KEY
LEFT JOIN STG_VLE v ON e.RESOURCE_KEY = v.RESOURCE_KEY
WHERE i.ENROLLMENT_KEY IS NULL OR v.RESOURCE_KEY IS NULL
HAVING COUNT(*) > 0;
