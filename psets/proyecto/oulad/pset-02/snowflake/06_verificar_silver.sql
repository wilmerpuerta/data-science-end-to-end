USE ROLE PSET2_PIPELINE;
USE WAREHOUSE PSET2_WH;
USE DATABASE PSET2_OULAD;
USE SCHEMA SILVER;

SELECT DATASET, METRIC, VALUE, DENOMINATOR
FROM DQ_SILVER_PROFILE ORDER BY DATASET, METRIC;

-- Comparar clics y filas representadas por cada módulo–edición.
WITH bronze AS (
    SELECT CODE_MODULE, CODE_PRESENTATION, COUNT(*) AS ROW_COUNT,
           SUM(SUM_CLICK) AS CLICK_COUNT
    FROM PSET2_OULAD.BRONZE.STG_STUDENT_VLE
    GROUP BY CODE_MODULE,CODE_PRESENTATION
), silver AS (
    SELECT CODE_MODULE, CODE_PRESENTATION, COUNT(*) AS DAILY_ROWS,
           SUM(SOURCE_ROW_COUNT) AS REPRESENTED_ROWS, SUM(CLICK_COUNT) AS CLICK_COUNT
    FROM SLV_ACTIVITY_DAILY GROUP BY CODE_MODULE,CODE_PRESENTATION
)
SELECT B.CODE_MODULE, B.CODE_PRESENTATION, B.ROW_COUNT, S.DAILY_ROWS,
       S.REPRESENTED_ROWS, B.CLICK_COUNT AS BRONZE_CLICKS, S.CLICK_COUNT AS SILVER_CLICKS,
       B.ROW_COUNT = S.REPRESENTED_ROWS AND B.CLICK_COUNT = S.CLICK_COUNT AS RECONCILED
FROM bronze B JOIN silver S USING(CODE_MODULE,CODE_PRESENTATION)
ORDER BY CODE_MODULE,CODE_PRESENTATION;

SELECT INITIAL_REGISTRATION_STATUS, COUNT(*) AS ENROLLMENTS
FROM SLV_REGISTRATION GROUP BY INITIAL_REGISTRATION_STATUS;

-- Resultados exclusivamente retrospectivos, separados de antecedentes.
SELECT TARGET_CLASS, COUNT(*) AS ENROLLMENTS
FROM SLV_OUTCOMES GROUP BY TARGET_CLASS;
