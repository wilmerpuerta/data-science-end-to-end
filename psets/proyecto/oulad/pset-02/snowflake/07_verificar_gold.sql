USE ROLE PSET2_PIPELINE;
USE WAREHOUSE PSET2_WH;
USE DATABASE PSET2_OULAD;
USE SCHEMA GOLD;

SELECT DATASET,METRIC,VALUE,DENOMINATOR
FROM DQ_GOLD_PROFILE ORDER BY DATASET,METRIC;

-- Uso dimensional: clics por edición y tipo de recurso.
SELECT E.CODE_MODULE,E.CODE_PRESENTATION,R.ACTIVITY_TYPE,
       SUM(A.CLICK_COUNT) AS CLICKS,SUM(A.SOURCE_ROW_COUNT) AS REPRESENTED_SOURCE_ROWS
FROM FACT_ACTIVITY_DAILY A
JOIN DIM_EDITION E ON A.EDITION_KEY=E.EDITION_KEY
JOIN DIM_RESOURCE R ON A.RESOURCE_KEY=R.RESOURCE_KEY
GROUP BY E.CODE_MODULE,E.CODE_PRESENTATION,R.ACTIVITY_TYPE
ORDER BY E.CODE_MODULE,E.CODE_PRESENTATION,R.ACTIVITY_TYPE;

-- Combinar hechos: agregar actividad antes de unirla a matrícula.
WITH ACTIVITY AS (
    SELECT ENROLLMENT_KEY,SUM(CLICK_COUNT) AS CLICKS
    FROM FACT_ACTIVITY_DAILY GROUP BY ENROLLMENT_KEY
)
SELECT E.EDITION_KEY,COUNT(*) AS ENROLLMENTS,
       COUNT_IF(A.ENROLLMENT_KEY IS NULL) AS WITHOUT_RECORDED_ACTIVITY,
       SUM(COALESCE(A.CLICKS,0)) AS RECORDED_CLICKS
FROM FACT_ENROLLMENT E
LEFT JOIN ACTIVITY A ON E.ENROLLMENT_KEY=A.ENROLLMENT_KEY
GROUP BY E.EDITION_KEY ORDER BY E.EDITION_KEY;

-- Referencia poblacional por corte, sin usar resultado final.
SELECT D.RELATIVE_DAY AS CUTOFF_DAY,COUNT(*) AS ELIGIBLE_ENROLLMENTS
FROM FACT_ENROLLMENT E
JOIN ENROLLMENT_WITHDRAWAL W ON E.ENROLLMENT_KEY=W.ENROLLMENT_KEY
CROSS JOIN DIM_RELATIVE_DAY D
WHERE D.IS_OBSERVATION_CUTOFF AND E.DATE_REGISTRATION<=0
  AND (W.DATE_UNREGISTRATION IS NULL OR W.DATE_UNREGISTRATION>D.RELATIVE_DAY)
GROUP BY D.RELATIVE_DAY ORDER BY D.RELATIVE_DAY;
