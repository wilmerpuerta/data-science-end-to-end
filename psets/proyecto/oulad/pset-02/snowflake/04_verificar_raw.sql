-- Consultas de verificación; utilizan el warehouse del proyecto.
USE ROLE PSET2_PIPELINE;
USE WAREHOUSE PSET2_WH;
USE DATABASE PSET2_OULAD;
USE SCHEMA RAW;

SELECT 'STUDENTINFO' AS tabla, COUNT(*) AS filas, COUNT(DISTINCT SOURCE_ROW_NUMBER) AS filas_origen_unicas, COUNT(DISTINCT SOURCE_SHA256) AS versiones FROM STUDENTINFO
UNION ALL SELECT 'STUDENTREGISTRATION',COUNT(*),COUNT(DISTINCT SOURCE_ROW_NUMBER),COUNT(DISTINCT SOURCE_SHA256) FROM STUDENTREGISTRATION
UNION ALL SELECT 'COURSES',COUNT(*),COUNT(DISTINCT SOURCE_ROW_NUMBER),COUNT(DISTINCT SOURCE_SHA256) FROM COURSES
UNION ALL SELECT 'VLE',COUNT(*),COUNT(DISTINCT SOURCE_ROW_NUMBER),COUNT(DISTINCT SOURCE_SHA256) FROM VLE
UNION ALL SELECT 'STUDENTVLE',COUNT(*),COUNT(DISTINCT SOURCE_ROW_NUMBER),COUNT(DISTINCT SOURCE_SHA256) FROM STUDENTVLE;
-- Esperados: 32593, 32593, 22, 6364 y 10655280 filas, respectivamente.
-- filas_origen_unicas = filas y una versión por tabla. No exige unicidad
-- de la clave natural de actividad, cuyos registros repetidos se preservan.

SELECT FINAL_RESULT,COUNT(*) AS matriculas
FROM STUDENTINFO GROUP BY FINAL_RESULT ORDER BY FINAL_RESULT;

SELECT COUNT_IF(IMD_BAND='') AS imd_vacio,COUNT_IF(IMD_BAND IS NULL) AS imd_null FROM STUDENTINFO;
-- 1111 vacíos y 0 NULL: Raw conserva valores originales, sin imputar.

SELECT SOURCE_FILE, STATUS, EXPECTED_ROWS, ACTUAL_ROWS, RUN_ID, RECORDED_AT
FROM INGESTION_LOG ORDER BY RECORDED_AT DESC;
