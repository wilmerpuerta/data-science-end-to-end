USE ROLE PSET2_PIPELINE;
USE WAREHOUSE PSET2_WH;
USE DATABASE PSET2_OULAD;
USE SCHEMA ANALYTICS;

SELECT COUNT(*) AS ROWS_TOTAL,
       COUNT(DISTINCT ENROLLMENT_KEY,CUTOFF_DAY) AS UNIQUE_KEYS
FROM OBT_FEATURES;

SELECT CUTOFF_DAY,COUNT(*) AS ENROLLMENTS,
       COUNT_IF(NOT HAS_RECORDED_ACTIVITY) AS WITHOUT_RECORDED_ACTIVITY,
       SUM(CLICKS_THROUGH_CUTOFF) AS RECORDED_CLICKS,
       SUM(CLICKS_CURRENT_14D) AS WINDOW_CLICKS,
       COUNT_IF(LAST_ACTIVITY_DAY>CUTOFF_DAY OR RECENCY_DAYS<0) AS INVALID_TIME_ROWS
FROM OBT_FEATURES GROUP BY CUTOFF_DAY ORDER BY CUTOFF_DAY;

-- Cero filas si no se añadieron por accidente las columnas prohibidas.
SELECT COLUMN_NAME FROM PSET2_OULAD.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA='ANALYTICS' AND TABLE_NAME='OBT_FEATURES'
  AND COLUMN_NAME IN ('FINAL_RESULT','TARGET_CLASS','TARGET_FAIL','DATE_UNREGISTRATION',
                     'IS_WITHDRAWN_WITHOUT_DATE','IS_OTHER_OUTCOME_WITH_WITHDRAWAL');

-- Diferencias de población respecto de Gold: deben ser cero en ambas direcciones.
WITH EXPECTED AS (
    SELECT E.ENROLLMENT_KEY,D.RELATIVE_DAY AS CUTOFF_DAY
    FROM PSET2_OULAD.GOLD.FACT_ENROLLMENT E
    JOIN PSET2_OULAD.GOLD.ENROLLMENT_WITHDRAWAL W ON E.ENROLLMENT_KEY=W.ENROLLMENT_KEY
    CROSS JOIN PSET2_OULAD.GOLD.DIM_RELATIVE_DAY D
    WHERE D.IS_OBSERVATION_CUTOFF AND E.DATE_REGISTRATION<=0
      AND (W.DATE_UNREGISTRATION IS NULL OR W.DATE_UNREGISTRATION>D.RELATIVE_DAY)
), MISSING AS (
    SELECT * FROM EXPECTED MINUS SELECT ENROLLMENT_KEY,CUTOFF_DAY FROM OBT_FEATURES
), EXTRA AS (
    SELECT ENROLLMENT_KEY,CUTOFF_DAY FROM OBT_FEATURES MINUS SELECT * FROM EXPECTED
)
SELECT 'missing' AS PROBLEM,COUNT(*) AS ROW_COUNT FROM MISSING
UNION ALL SELECT 'extra',COUNT(*) FROM EXTRA;
